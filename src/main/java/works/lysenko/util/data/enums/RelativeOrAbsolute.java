package works.lysenko.util.data.enums;

/**
 * The RelativeOrAbsolute enum represents a type of measurement which can be either
 * an absolute value or a relative value.
 */
public enum RelativeOrAbsolute {

    /**
     * Absolute measurement value.
     */
    ABSOLUTE,

    /**
     * Relative measurement value.
     */
    RELATIVE
}
